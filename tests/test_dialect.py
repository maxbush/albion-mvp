# ── is_postgres / pg_dsn / translate_qmarks ──────────────────────────

def test_is_postgres():
    assert is_postgres("postgres://u:p@h/db")
    assert is_postgres("postgresql://u:p@h/db")
    assert is_postgres("postgresql+asyncpg://u:p@h/db")
    assert not is_postgres("albion.db")
    assert not is_postgres("sqlite+aiosqlite:///./albion.db")
    assert not is_postgres(None)


def test_pg_dsn_normalizes_scheme():
    assert pg_dsn("postgres://u:p@h/db") == "postgresql://u:p@h/db"
    assert pg_dsn("postgresql+asyncpg://u:p@h/db") == "postgresql://u:p@h/db"
    assert pg_dsn("postgresql://u:p@h/db") == "postgresql://u:p@h/db"


def test_translate_qmarks_basic():
    sql = "SELECT * FROM t WHERE a=? AND b IN (?,?) LIMIT ?"
    assert translate_qmarks(sql) == "SELECT * FROM t WHERE a=$1 AND b IN ($2,$3) LIMIT $4"


def test_translate_qmarks_skips_literals():
    sql = "SELECT 'что?' AS q, a FROM t WHERE a=? AND b='?'"
    out = translate_qmarks(sql)
    assert "'что?'" in out and "b='?'" in out
    assert "a=$1" in out
    # литерал с экранированной кавычкой
    assert translate_qmarks("SELECT 'It''s ?' , ? ") == "SELECT 'It''s ?' , $1 "


def test_ddl_pg_transforms():
    ddl = ddl_pg(SCHEMA_SQL)
    assert "PRAGMA" not in ddl
    assert "AUTOINCREMENT" not in ddl
    assert "GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in ddl
    assert "CREATE TABLE IF NOT EXISTS users" in ddl
    assert "TIMESTAMP" not in ddl                          # → TEXT (ISO-строки)
    assert "TEXT DEFAULT (albion_now())" in ddl            # CURRENT_TIMESTAMP → f()


